// ---------------------------------------------------------------------------
// 校验：每条样本必须确实命中源正则（把 WhatWaf 的 Python 正则按 JS 语义转写，
// 仅替换 \A→^；其余 .、\d、\w、{n,m} 语义相同）。不符 = 映射错误，立即失败。
// ---------------------------------------------------------------------------
let fail = 0;
function check(samples, origin) {
  for (const s of samples) {
    let re = s.sourceRule.replace(/\\A/g, '^');
    // header 型：某些源正则（如 cloudfront 的 x.amz.cf.id）匹配的是头 **key** 形态，
    // 以 key + ' ' + value 拼接后统一匹配；body/cookie 型直接用 value。
    const hay = s.kind === 'header' ? `${s.key} ${s.sample}` : s.sample;
    try {
      const ok = new RegExp(re, 'i').test(hay);
      if (!ok) {
        console.error(`✗ [${origin}] ${s.ours}：样本「${hay}」不受源正则「${s.sourceRule}」命中 —— 映射错了`);
        fail++;
      }
    } catch (e) {
      console.error(`✗ [${origin}] ${s.ours}：正则「${s.sourceRule}」非法（${e.message}）`);
      fail++;
    }
  }
}
