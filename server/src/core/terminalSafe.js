// ============================================================================
// terminalSafe.js —— 终端 / 日志出口的**控制序列**消毒
// ============================================================================
// 威胁模型：扫描器会把**目标可控**的字符串打印到操作员的终端与 engine.log ——
// 报错原文、响应片段、WAF 指纹文本、参数名，以及拖库拿到的库名/表名/列名/单元格值。
// 不消毒控制字符的后果不是"输出难看"：
//   · OSC `ESC ] 0 ; … BEL`  → 改写操作员终端**标题**（可写成"这个库已备份完成"之类）；
//   · OSC 8 `ESC ] 8 ; ; http://evil BEL 文字 ESC ] 8 ; ; BEL`
//                            → 在 Windows Terminal / iTerm / VTE 系里生成**可点击超链接**，
//                              显示文字与真实目标可以完全不同（终端版钓鱼）；
//   · CSI（光标移动、擦除行）→ 覆盖刚刚打印的行，把一次扫描的结果改写成别的内容；
//   · CR (`\r`)              → 回车覆盖当前行；换行则能**伪造日志行**（时间戳+level 都齐的假记录）。
// 这类"输出边界没设防"的坑本仓已在 HTML / markdown / CSV 三个出口各修过一次，本模块是第四个出口。
//
// 口径：**转义成可见标记，而不是静默删除**。拖库结果里真含控制字符是重要情报
// （例如目标把二进制塞进了 VARCHAR），悄悄删掉等于替目标改了证据。
// ============================================================================

// \n 与 \t 保留：它们承载的是排版（多行输出与表格分隔），不携带终端指令语义。
const CONTROL_RE = /[\x00-\x08\x0b\x0c\x0d\x0e-\x1f\x7f\u0080-\u009f]/g;

const asMarker = (c) => `<U+${c.charCodeAt(0).toString(16).toUpperCase().padStart(4, '0')}>`;

/**
 * 把字符串里的终端控制序列转成可见标记。
 * @param {unknown} v 任意值（目标可控数据也直接吃）
 * @returns {string} 可安全写进终端 / 日志文件的文本
 */
export function sanitizeForTerminal(v) {
  return String(v ?? '').replace(CONTROL_RE, asMarker);
}

/**
 * 幂等性自检用的说明：转义产物（`<U+001B>` 之类）本身不含控制字符，
 * 所以对同一字符串重复调用不会改变结果 —— 多个出口都调它不会出现"套娃转义"。
 */
export default sanitizeForTerminal;
