// 通用拦截页（block page）特征库 —— 厂商硬签名之外的兜底识别层。
//
// 为什么要这一层（实战缺陷）：
//   WafIdentifier 原先只比对 wafRules.js 的 62 家厂商签名，「识别不出」被当成「不存在」。
//   但厂商签名本质是静态快照：国产云 WAF 拦截页按月改版、CDN 透传的自定义规则页、
//   自建 ModSecurity 被改写过的拒绝页，一律不在表内 → 漏识别。漏识别的代价不是「少一条提示」，
//   而是引擎继续用裸 payload 撞同一面墙（整轮请求全被拦 → 0 检出）。
//   本层只回答一个问题：「这个响应是不是一个拦截页」，不试图说出厂商名。
//
// 为什么判据必须保守（重要）：
//   误判「拦截页」的代价是发包形态被改（tamper 重跑 = 全站请求翻倍）。因此：
//   1) 状态码门槛：只有 status ∈ {403,406,418,429,503} 才允许「任一通用特征」触发；
//      其余状态码（302/400/500…）语义混杂，即使正文出现拦截字样也不判定——宁可不判也不猜。
//   2) status === 200 时必须命中「成对强特征」：拦截语义 + 处置语义同时出现才算
//      （如「含有攻击特征」+「已被…拦截」；「事件ID」+「错误码」且两者后面都跟着实际取值）。
//      这条约束的存在理由：帮助文档/产品手册类 200 页面满屏「防火墙 / WAF / 拦截」，
//      单词命中会把整个文档站误判成拦截页（单测显式覆盖该反例）。
//   3) 处置语义只认**完成时**句式（「已被…拦截」/「has been blocked」），
//      刻意不收「会被拦截 / 将拦截 / 拦截规则怎么配」这类讲解式现在时——文档里全是后者。
//   4) 置信度恒 ≤ GENERIC_CONFIDENCE_CAP（0.6），低于 WafIdentifier.WAF_HIGH_CONFIDENCE（0.8）
//      → 通用命中只用于「提示 + 发包形态建议（blockPolicy）」，永不触发 autoRetry 整站重跑。
//   5) 成对特征用 `^` + 双前瞻实现：既保证「同一响应里 A 与 B 都出现」，又让引擎只在 0 号位
//      试一次（非锚定的 (?=[\s\S]*A) 在长正文上会退化成 O(n²)）；正文另做长度截断。
//   6) 正则一律不带 /g：detectGenericBlock 是纯函数，lastIndex 状态会污染跨调用结果。
//
// 零依赖、纯函数、零额外发包：只做字符串匹配，不触碰网络与配置。

// 拦截语义状态码集合（429/503 同时是容量信号，退避交由 blockPolicy 处理）
export const GENERIC_BLOCK_STATUSES = new Set([403, 406, 418, 429, 503]);

// 限流/过载状态码（blockPolicy 仅在此集合内读取 Retry-After）
export const RATE_LIMIT_STATUSES = new Set([429, 503]);

// 通用拦截页候选的 vendor 标记（区别于 62 家厂商名：调用方据此知道「只确认被拦、不知被谁拦」）
export const GENERIC_BLOCK_VENDOR = 'generic_block';

// 置信度：单特征 0.55，多特征交叉每 +1 命中加 0.05，封顶 0.6。
// 封顶刻意压在 WAF_HIGH_CONFIDENCE(0.8) 之下——通用签名不足以支撑「整站套 tamper 重跑」这类放大流量的决策。
const CONFIDENCE_BASE = 0.55;
const CONFIDENCE_STEP = 0.05;
export const GENERIC_CONFIDENCE_CAP = 0.6;

// 参与匹配的文本上限（拦截文案集中在 <title>/首屏，超长正文没必要整篇扫）
const HAYSTACK_CAP = 200_000;

// 处置语义（强特征里的「已被处置」半边）：只认完成时，且限定在请求/访问/IP 主语上。
const DISPOSITION = String.raw`已被[\s\S]{0,16}(?:拦截|阻断|拒绝|封禁)|您的?(?:请求|访问|ip address)[^.\n<]{0,24}(?:has been|was) (?:blocked|denied|refused)`;

/**
 * 成对强特征：a 与 b 必须在同一段文本里同时出现（锚定 0 号位的双前瞻，单次线性扫描）。
 * @param {string} a 拦截语义子模式
 * @param {string} b 处置语义子模式
 * @returns {RegExp}
 */
const pair = (a, b) => new RegExp(`^(?=[\\s\\S]*(?:${a}))(?=[\\s\\S]*(?:${b}))`, 'i');

/**
 * 单特征强签名：本身即无歧义的拦截页标记（不是「提到拦截」，而是「拦截页才会输出」）。
 * @param {string} src
 * @returns {RegExp}
 */
const solo = (src) => new RegExp(`^(?=[\\s\\S]*(?:${src}))`, 'i');

