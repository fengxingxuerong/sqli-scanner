// 参与匹配的响应头白名单：这几个头常直接暴露拦截或人机校验语义（如 set-cookie 里的校验 cookie 名）。
// 刻意不做「全量头部拼接」——x-request-id / x-powered-by 之类正常头会把通用匹配的区分度稀释掉。
const HEADER_KEYS = new Set(['server', 'via', 'set-cookie', 'refresh', 'location']);
// 另收特征性命名的拦截相关头（x-powered-by-safedog、x-waf-message、x-block-id …）
const HEADER_KEY_HINTS = /waf|safedog|yunsuo|block|shield|deny|firewall/i;

// 归一化匹配文本：白名单头值 + 正文，截断到 HAYSTACK_CAP
function buildHaystack(res) {
  const headers = res?.headers;
  let head = '';
  if (headers && typeof headers === 'object') {
    for (const [k, v] of Object.entries(headers)) {
      const key = String(k).toLowerCase();
      if (!HEADER_KEYS.has(key) && !HEADER_KEY_HINTS.test(key)) continue;
      if (v == null) continue;
      head += `${key}: ${Array.isArray(v) ? v.join(', ') : String(v)}\n`;
    }
  }
  const body = String(res?.body ?? res?.data ?? '');
  const text = head + body;
  return text.length > HAYSTACK_CAP ? text.slice(0, HAYSTACK_CAP) : text;
}

/**
 * 判定一个响应是否为「通用拦截页」（纯函数，零副作用、零发包）。
 *
 * @param {{status:number, headers?:object, body?:string}} res 指纹阶段已抓取的基线响应（或任意响应）
 * @returns {{id:string, vendor:'generic_block', confidence:number, evidence:string, hint:string, family:string, matchedIds:string[], status:number}|null}
 *          命中返回候选（confidence 恒 ≤ 0.6），未命中返回 null
 */
export function detectGenericBlock(res) {
  const status = Number(res?.status);
  if (!Number.isFinite(status)) return null; // 无状态码（网络失败 / direct 模式）不判定
  const isBlockStatus = GENERIC_BLOCK_STATUSES.has(status);
  // 只在两种情形下下判断：拦截状态码（可接受弱特征）、200（必须强特征）。其余一律 null。
  if (!isBlockStatus && status !== 200) return null;

  const text = buildHaystack(res);
  if (!text) return null;

  const strongHits = GENERIC_BLOCK_SIGS.filter((s) => s.sig.test(text));
  // 拦截状态码下仍要求「有文案」：裸 403（目录禁止访问、业务鉴权失败）不代表 WAF 拦截，
  // 此时改发包形态毫无意义，只会白白放大流量。
  const softHits = isBlockStatus ? GENERIC_SOFT_SIGS.filter((s) => s.sig.test(text)) : [];
  const hits = strongHits.concat(softHits);
  if (hits.length === 0) return null;

  // 主证据取首个强特征（hint/family 更能说明「被什么形态的拦截页挡住」），无强特征才退到弱特征
  const primary = hits[0];
  const matchedIds = hits.map((s) => s.id);
  const confidence = Math.min(GENERIC_CONFIDENCE_CAP, CONFIDENCE_BASE + (hits.length - 1) * CONFIDENCE_STEP);
  return {
    id: primary.id,
    vendor: GENERIC_BLOCK_VENDOR,
    confidence,
    // evidence 同时写明 status 与命中的特征 id：拦截结论必须可复核（哪个码 + 哪几条特征）
    evidence: `status=${status}; generic_block: ${matchedIds.join(', ')}`,
    hint: primary.hint,
    family: primary.family,
    matchedIds,
    status,
  };
}

export default detectGenericBlock;
