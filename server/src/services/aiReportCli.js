// ============================================================================
// aiReportCli.js —— [D205] CLI 侧 AI 报告落盘（`--ai-report [dir]`）
//
// 为什么单独一层：REST 侧有 `POST /api/scan/:id/report/ai`，CLI 侧此前**完全没有入口**——
// CLI 扫描产物（`reports/*.json`）只能靠外部脚本喂 `generateAiReport()`（D192 冒烟就是这样跑的）。
// 本层只做三件事：
//   ① 预检：`--ai-report` 给了但 AI 环境变量不全 → **开扫前就拒绝启动**（本仓红线：收参数不生效
//      比报错更糟，扫描白跑 3 分钟才发现没配上是最坏形态）；
//   ② 目录语义：不带值 ⇒ `<--out 目录或当前目录>/ai-report/`；带值 ⇒ 直接写该目录（与 --fix-prompt 同）；
//   ③ 落盘：`ai-report.md`（正文）+ `ai-report.json`（元信息：模型链/耗时/审阅状态/源报告）。
// 刻意不做：改写扫描结论、抬高退出码等级。AI 报告失败 = 执行失败（1），
// 绝不把「没检出」说成「有洞」，也不把「有洞」说成「没洞」。
// ============================================================================
import { mkdirSync, writeFileSync, statSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { AppError, ErrorCode } from '../core/errors.js';
import { generateAiReport, isAiReportEnabled, listAiConfigs } from './ReportAI.js';

/** AI 报告单次生成的默认超时（三模型串行，实测本机网关 117~180s，留足余量） */
const AI_REPORT_TIMEOUT_MS = 600000;

/**
 * [D205] 预检：`--ai-report` 已启用但 env 不全时**直接抛错**（在开扫前调用）。
 * 未启用 `--ai-report` 时什么都不做（零行为变更）。
 * @param {object} args CLI 参数
 * @returns {void}
 * @throws {Error} AI 环境变量缺失时
 */
export function assertAiReportUsable(args) {
  if (!args?.aiReport) return;
  if (isAiReportEnabled()) return;
  throw new AppError(
    ErrorCode.AI_REPORT_DISABLED,
    '--ai-report 需要先配置 AI 网关环境变量：'
    + 'AI_REPORT_API_BASE（完整的 chat/completions 端点）+ AI_REPORT_KEY_1（或 _2/_3）。'
    + '自建/本机网关常强制 provider/model 全名，另需 AI_REPORT_MODEL_1/2/3 覆盖裸名。'
    + '详见 docs/api.md「AI 报告」一节。',
  );
}

/**
 * [D205] `--ai-report` 的落点目录：带值用该目录；不带值用 `<--out 目录或当前目录>/ai-report`。
 * 语义与 `--fix-prompt` 一致（`--out` 是文件就取它所在目录）。
 * @param {object} args CLI 参数（用 `aiReport` 与 `out`）
 * @returns {string} 绝对目录
 */
export function resolveAiReportDir(args) {
  const explicit = typeof args?.aiReport === 'string' && args.aiReport.trim() ? args.aiReport : null;
  if (explicit) return resolve(explicit);
  const out = typeof args?.out === 'string' && args.out.trim() ? args.out : process.cwd();
  try {
    if (statSync(out).isDirectory()) return join(resolve(out), 'ai-report');
  } catch {
    if (/[\\/]$/.test(out)) return join(resolve(out), 'ai-report');
  }
  return join(resolve(dirname(out)), 'ai-report');
}

/**
 * [D205] 渲染 `ai-report.md`：头部注释写清来源报告、模型链、耗时、审阅状态，
 * 便于复核「这份报告是谁生成的、用了什么口径」。正文原样保留模型输出。
 * @param {{content?: string, model?: string, reviewNote?: string, pipeline?: string}} result generateAiReport 的返回
 * @param {{sourceReport?: string, elapsedMs?: number, masked?: boolean}} meta 元信息
 * @returns {string} Markdown 文本
 */
export function renderAiReportDoc(result, meta = {}) {
  const lines = [
    '<!-- generated by sqli-scanner --ai-report (D205) -->',
    `<!-- source report: ${meta.sourceReport || 'unknown'} -->`,
    `<!-- pipeline: ${result?.pipeline || 'analyst→writer→reviewer'} | models: ${result?.model || 'unknown'} -->`,
    `<!-- elapsed: ${meta.elapsedMs ?? 'NA'}ms | ${result?.reviewNote || '未审阅'} -->`,
    `<!-- 数据脱敏: ${meta.masked ? '开启（host/路径为占位符，PoC 需人工回填）' : '关闭（AI_REPORT_MASK=0，host/路径原样）'} -->`,
    '',
    String(result?.content || ''),
  ];
  return lines.join('\n');
}

/**
 * 报告侧事实（缺字段一律 null，不编造）。
 * @param {object} report 引擎报告
 * @returns {{scanId: string|null, target: string|null, verdict: string|null, vulnCount: number}} 报告事实
 */
function reportFacts(report) {
  const r = report || {};
  return {
    scanId: r.scanId || null,
    target: r.target?.baseUrl || null,
    verdict: r.summary?.verdict || null,
    vulnCount: Array.isArray(r.vulns) ? r.vulns.length : 0,
  };
}

/**
 * 模型侧事实（用了哪条链、耗时、是否脱敏）。
 * @param {object} result 模型返回
 * @param {{elapsedMs?: number, masked?: boolean}} meta 元信息
 * @returns {{model: string|null, pipeline: string|null, reviewNote: string|null, elapsedMs: number|null, masked: boolean, roles: object[]}} 模型事实
 */
function modelFacts(result, meta) {
  const m = result || {};
  return {
    model: m.model || null,
    pipeline: m.pipeline || null,
    reviewNote: m.reviewNote || null,
    elapsedMs: meta.elapsedMs || null,
    masked: meta.masked !== false,
    roles: listAiConfigs(),
  };
}

/**
 * [D205] ai-report.json 的内容（拆成三个函数只为压圈复杂度——
 * 每个 `??`/`||` 在门禁里都算一个分支，堆在一个函数里必超 15）。
 * @param {object} report 引擎报告
 * @param {object} result 模型返回
 * @param {{elapsedMs?: number, masked?: boolean}} meta 元信息
 * @returns {object} 可序列化的元信息对象
 */
function buildAiReportMeta(report, result, meta) {
  return {
    generatedAt: new Date().toISOString(),
    ...reportFacts(report),
    ...modelFacts(result, meta),
  };
}

/**
 * [D205] 纯落盘：把 generateAiReport 的结果写成 `ai-report.md` + `ai-report.json`。
 * 抽出来是为了可单测（不依赖 env 快照与网络），writeAiReport 只负责「预检 + 调模型 + 调本函数」。
 * @param {string} dir 落点目录（不存在则创建）
 * @param {{content?: string, model?: string, reviewNote?: string, pipeline?: string}} result 模型返回
 * @param {object} report 引擎报告（只取 scanId/target/verdict/vuln 数写进元信息）
 * @param {{elapsedMs?: number, masked?: boolean}} meta 元信息
 * @returns {{file: string, metaFile: string, bytes: number}} 落盘路径与正文字节数
 */
export function writeAiReportFiles(dir, result, report, meta = {}) {
  mkdirSync(dir, { recursive: true });
  const file = join(dir, 'ai-report.md');
  const metaFile = join(dir, 'ai-report.json');
  writeFileSync(file, renderAiReportDoc(result, {
    sourceReport: report?.scanId || report?.target?.baseUrl || 'unknown',
    elapsedMs: meta.elapsedMs,
    masked: meta.masked,
  }), 'utf-8');
  writeFileSync(metaFile, JSON.stringify(buildAiReportMeta(report, result, meta), null, 2), 'utf-8');
  return { file, metaFile, bytes: Buffer.byteLength(String(result?.content || ''), 'utf8') };
}

/**
 * [D205] 生成并落盘 AI 报告。**不抛异常**：失败以 `{ok:false, error}` 返回，
 * 由调用方决定退出码（扫描结论不受影响）。
 * @param {object} report 引擎报告
 * @param {object} args CLI 参数
 * @returns {Promise<{ok: boolean, dir?: string, file?: string, metaFile?: string, model?: string, elapsedMs?: number, reviewNote?: string, bytes?: number, error?: string}>} 落盘结果
 */
export async function writeAiReport(report, args) {
  try {
    if (!isAiReportEnabled()) return { ok: false, error: 'AI 网关未配置（AI_REPORT_API_BASE / AI_REPORT_KEY_1）' };
    const dir = resolveAiReportDir(args);
    const t0 = Date.now();
    const result = await generateAiReport(report, AI_REPORT_TIMEOUT_MS);
    const elapsedMs = Date.now() - t0;
    const masked = process.env.AI_REPORT_MASK !== '0';
    const { file, metaFile, bytes } = writeAiReportFiles(dir, result, report, { elapsedMs, masked });
    return { ok: true, dir, file, metaFile, model: result?.model, elapsedMs, reviewNote: result?.reviewNote, bytes };
  } catch (e) {
    return { ok: false, error: e?.message || String(e) };
  }
}

export default { assertAiReportUsable, resolveAiReportDir, renderAiReportDoc, writeAiReportFiles, writeAiReport };
